/// Which 実況 channel (jk number) a broadcast service belongs to.
///
/// Generated from the service list in NicoJK's jkch.sh.txt, keeping the channels NX-Jikkyo carries.
/// Terrestrial services are keyed by service id alone (the area is part of it), others by
/// network id << 16 | service id.
enum ChannelTable {
    static func jikkyoID(networkID: Int, serviceID: Int) -> Int? {
        if (0x7880...0x7FEF).contains(networkID) {
            // service type and number bits vary between the sub-channels of a station
            return byTerrestrial[serviceID & ~0x0187]
        }
        return byNetworkService[networkID << 16 | serviceID]
    }

    private static let byTerrestrial = invert(terrestrial)
    private static let byNetworkService = invert(satellite)

    private static func invert(_ table: [Int: [Int]]) -> [Int: Int] {
        var result: [Int: Int] = [:]
        for (jk, keys) in table {
            for k in keys { result[k] = jk }
        }
        return result
    }

